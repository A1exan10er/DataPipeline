#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
cd "$REPO_ROOT"

ACTION="${1:-start}"
SESSION="${EVENT_LISTENER_SESSION:-qa_event_listener}"
JOB_DB="${EVENT_LISTENER_JOB_DB:-outputs/event_listener/jobs.db}"
OUTPUT_DIR="${EVENT_LISTENER_OUTPUT_DIR:-outputs/event_listener}"
LOG_FILE="${EVENT_LISTENER_LOG_FILE:-$OUTPUT_DIR/listener.log}"
CONTROL_DIR="${EVENT_LISTENER_CONTROL_DIR:-$OUTPUT_DIR/control}"
PID_FILE="${EVENT_LISTENER_PID_FILE:-$CONTROL_DIR/listener.pid}"
ENABLED_FILE="${EVENT_LISTENER_ENABLED_FILE:-$CONTROL_DIR/listener.enabled}"
SETTINGS_FILE="${EVENT_LISTENER_SETTINGS_FILE:-$CONTROL_DIR/listener-settings.env}"
DCS_CONFIG_FILE="${DCS_CONFIG_FILE:-$HOME/DataPipeline/dcp-sdk/dcs_config.json}"
DC_ROOT="${DC_ROOT:-$REPO_ROOT/dcp-sdk}"
MOUNT_PREFIX="${MOUNT_PREFIX:-/mnt/nas/database/verified}"
NAS_PREFIX="${NAS_PREFIX:-/volume1/database/verified,/database/verified}"
QA_PYTHON="${QA_PYTHON:-datapipeline-env/bin/python}"
PHASES="${PHASES:-1,2,3,6,7}"
WORKERS="${WORKERS:-1}"
PHASE6_PROFILE="${PHASE6_PROFILE:-video_only}"
PHASE6_VIDEO_OUTPUT_MODE="${PHASE6_VIDEO_OUTPUT_MODE:-sidecar}"
PHASE6_SIDECAR_FILENAME="${PHASE6_SIDECAR_FILENAME:-video_rotated_180.mp4}"
DISABLE_QUALITY_LABEL_FILTER="${DISABLE_QUALITY_LABEL_FILTER:-1}"
EVENT_BATCH_SIZE="${EVENT_BATCH_SIZE:-16}"
EVENT_QUEUE_NAME="${EVENT_QUEUE_NAME:-qa_pipeline.listen_episode_verified.v2}"
EVENT_DATE="${EVENT_DATE:-}"
EVENT_DATE_FROM="${EVENT_DATE_FROM:-}"
EVENT_DATE_TO="${EVENT_DATE_TO:-}"
STABILITY_INTERVAL="${STABILITY_INTERVAL:-3}"
STABILITY_TIMEOUT="${STABILITY_TIMEOUT:-90}"
MIN_FREE_MEM_GB="${MIN_FREE_MEM_GB:-6}"
MAX_LOAD_RATIO="${MAX_LOAD_RATIO:-0.75}"
RESOURCE_MAX_WAIT_SECONDS="${RESOURCE_MAX_WAIT_SECONDS:-300}"
RETENTION_DAYS="${RETENTION_DAYS:-14}"
RETENTION_MAX_RUNS="${RETENTION_MAX_RUNS:-0}"
RETENTION_MAX_GB="${RETENTION_MAX_GB:-0}"
TASK_DB_ENV_FILE="${TASK_DB_ENV_FILE:-$HOME/.qa_task_db_env}"
QA_DCS_NOTIFY_ENABLED="${QA_DCS_NOTIFY_ENABLED:-1}"
QA_DCS_NOTIFY_DRY_RUN="${QA_DCS_NOTIFY_DRY_RUN:-0}"
QA_DCS_NOTIFY_WAIT="${QA_DCS_NOTIFY_WAIT:-1}"
QA_DCS_NOTIFY_EVENT="${QA_DCS_NOTIFY_EVENT:-qa.episode_abnormal.detected}"
QA_DCS_NOTIFY_STATUSES="${QA_DCS_NOTIFY_STATUSES:-fail}"
QA_DCS_NOTIFY_ACTIONABLE_STATUSES="${QA_DCS_NOTIFY_ACTIONABLE_STATUSES:-needs_review}"
QA_DCS_NOTIFY_ACTIONABLE_CHECKS="${QA_DCS_NOTIFY_ACTIONABLE_CHECKS:-}"
QA_DCS_NOTIFY_EXCLUDE_CHECKS="${QA_DCS_NOTIFY_EXCLUDE_CHECKS:-timestamps_raw_inconsistency,quality_label_unexpected}"
BACKEND="${EVENT_LISTENER_BACKEND:-auto}"
SYSTEMD_SERVICE="${EVENT_LISTENER_SYSTEMD_SERVICE:-datapipeline-event-listener.service}"

# The dashboard supervisor explicitly opts into the last known-good settings.
# Interactive/API starts keep the values supplied in their current environment.
if [[ "${EVENT_LISTENER_USE_SAVED_SETTINGS:-0}" == "1" && -f "$SETTINGS_FILE" ]]; then
  # The file is generated by persist_settings() using shell-safe %q values.
  # shellcheck disable=SC1090
  source "$SETTINGS_FILE"
  SESSION="${EVENT_LISTENER_SESSION:-$SESSION}"
  JOB_DB="${EVENT_LISTENER_JOB_DB:-$JOB_DB}"
  OUTPUT_DIR="${EVENT_LISTENER_OUTPUT_DIR:-$OUTPUT_DIR}"
  LOG_FILE="${EVENT_LISTENER_LOG_FILE:-$LOG_FILE}"
  BACKEND="${EVENT_LISTENER_BACKEND:-$BACKEND}"
  SYSTEMD_SERVICE="${EVENT_LISTENER_SYSTEMD_SERVICE:-$SYSTEMD_SERVICE}"
fi
# Recalculate derived paths after loading saved settings. Explicit control paths
# remain supported for tests and non-default installations.
CONTROL_DIR="${EVENT_LISTENER_CONTROL_DIR:-$OUTPUT_DIR/control}"
PID_FILE="${EVENT_LISTENER_PID_FILE:-$CONTROL_DIR/listener.pid}"
ENABLED_FILE="${EVENT_LISTENER_ENABLED_FILE:-$CONTROL_DIR/listener.enabled}"
SETTINGS_FILE="${EVENT_LISTENER_SETTINGS_FILE:-$CONTROL_DIR/listener-settings.env}"
if [[ "$BACKEND" != "auto" && "$BACKEND" != "tmux" && "$BACKEND" != "process" && "$BACKEND" != "systemd" ]]; then
  echo "EVENT_LISTENER_BACKEND 只能是 auto、tmux、process 或 systemd"
  exit 2
fi
if [[ ! "$SYSTEMD_SERVICE" =~ ^[A-Za-z0-9_.@-]+\.service$ ]]; then
  echo "EVENT_LISTENER_SYSTEMD_SERVICE 格式无效"
  exit 2
fi
for value_name in EVENT_DATE EVENT_DATE_FROM EVENT_DATE_TO; do
  value="${!value_name}"
  if [[ -n "$value" && "$value" != "today" && "$value" != "yesterday" && ! "$value" =~ ^[0-9]{8}$ ]]; then
    echo "$value_name 必须是 YYYYMMDD、today 或 yesterday"
    exit 2
  fi
done
if [[ -n "$EVENT_DATE" && ( -n "$EVENT_DATE_FROM" || -n "$EVENT_DATE_TO" ) ]]; then
  echo "EVENT_DATE 不能与 EVENT_DATE_FROM/EVENT_DATE_TO 同时使用"
  exit 2
fi
if [[ "$EVENT_DATE_FROM" =~ ^[0-9]{8}$ && "$EVENT_DATE_TO" =~ ^[0-9]{8}$ && "$EVENT_DATE_FROM" > "$EVENT_DATE_TO" ]]; then
  echo "EVENT_DATE_FROM 必须早于或等于 EVENT_DATE_TO"
  exit 2
fi
tmux_installed() {
  command -v tmux >/dev/null 2>&1
}

tmux_available() {
  [[ "$BACKEND" != "process" ]] && tmux_installed
}

tmux_running() {
  tmux_installed && tmux has-session -t "$SESSION" 2>/dev/null
}

systemd_running() {
  [[ "$BACKEND" == "systemd" ]] \
    && systemctl --user is-active --quiet "$SYSTEMD_SERVICE" 2>/dev/null
}

managed_process_pid() {
  [[ -f "$PID_FILE" ]] || return 1
  local pid cmdline
  pid="$(tr -d '[:space:]' < "$PID_FILE" 2>/dev/null || true)"
  [[ "$pid" =~ ^[0-9]+$ ]] || return 1
  kill -0 "$pid" 2>/dev/null || return 1
  [[ -r "/proc/$pid/cmdline" ]] || return 1
  cmdline="$(tr '\0' ' ' < "/proc/$pid/cmdline" 2>/dev/null || true)"
  [[ "$cmdline" == *"Werkzeuge/listen_episode_verified.py"* && "$cmdline" == *"serve"* ]] || return 1
  printf '%s\n' "$pid"
}

listener_running() {
  systemd_running || tmux_running || managed_process_pid >/dev/null
}

persist_settings() {
  mkdir -p "$CONTROL_DIR"
  local temporary="$SETTINGS_FILE.tmp.$$" name
  : > "$temporary"
  chmod 600 "$temporary"
  printf 'EVENT_LISTENER_SESSION=%q\n' "$SESSION" >> "$temporary"
  printf 'EVENT_LISTENER_JOB_DB=%q\n' "$JOB_DB" >> "$temporary"
  printf 'EVENT_LISTENER_OUTPUT_DIR=%q\n' "$OUTPUT_DIR" >> "$temporary"
  printf 'EVENT_LISTENER_LOG_FILE=%q\n' "$LOG_FILE" >> "$temporary"
  printf 'EVENT_LISTENER_BACKEND=%q\n' "$BACKEND" >> "$temporary"
  printf 'EVENT_LISTENER_SYSTEMD_SERVICE=%q\n' "$SYSTEMD_SERVICE" >> "$temporary"
  for name in \
    DCS_CONFIG_FILE DC_ROOT MOUNT_PREFIX NAS_PREFIX QA_PYTHON PHASES WORKERS \
    PHASE6_PROFILE PHASE6_VIDEO_OUTPUT_MODE PHASE6_SIDECAR_FILENAME DISABLE_QUALITY_LABEL_FILTER \
    EVENT_BATCH_SIZE EVENT_QUEUE_NAME EVENT_DATE EVENT_DATE_FROM EVENT_DATE_TO \
    STABILITY_INTERVAL STABILITY_TIMEOUT MIN_FREE_MEM_GB MAX_LOAD_RATIO RESOURCE_MAX_WAIT_SECONDS \
    RETENTION_DAYS RETENTION_MAX_RUNS RETENTION_MAX_GB TASK_DB_ENV_FILE \
    QA_DCS_NOTIFY_ENABLED QA_DCS_NOTIFY_DRY_RUN QA_DCS_NOTIFY_WAIT QA_DCS_NOTIFY_EVENT \
    QA_DCS_NOTIFY_STATUSES QA_DCS_NOTIFY_ACTIONABLE_STATUSES QA_DCS_NOTIFY_ACTIONABLE_CHECKS \
    QA_DCS_NOTIFY_EXCLUDE_CHECKS; do
    printf '%s=%q\n' "$name" "${!name-}" >> "$temporary"
  done
  mv "$temporary" "$SETTINGS_FILE"
}

mark_enabled() {
  mkdir -p "$CONTROL_DIR"
  printf 'enabled\n' > "$ENABLED_FILE"
}

mark_disabled() {
  rm -f "$ENABLED_FILE"
}

start_foreground() {
  mkdir -p "$OUTPUT_DIR" "$CONTROL_DIR"
  set -a
  [[ -f "$TASK_DB_ENV_FILE" ]] && source "$TASK_DB_ENV_FILE"
  set +a
  export DCS_CONFIG_FILE QA_DCS_NOTIFY_ENABLED QA_DCS_NOTIFY_DRY_RUN QA_DCS_NOTIFY_WAIT
  export QA_DCS_NOTIFY_EVENT QA_DCS_NOTIFY_STATUSES QA_DCS_NOTIFY_ACTIONABLE_STATUSES
  export QA_DCS_NOTIFY_ACTIONABLE_CHECKS QA_DCS_NOTIFY_EXCLUDE_CHECKS
  local args=(
    Werkzeuge/listen_episode_verified.py serve
    --job-db "$JOB_DB"
    --output-dir "$OUTPUT_DIR"
    --dc-root "$DC_ROOT"
    --mount-prefix "$MOUNT_PREFIX"
    --nas-prefix "$NAS_PREFIX"
    --qa-python "$QA_PYTHON"
    --queue-name "$EVENT_QUEUE_NAME"
    --phases "$PHASES"
    --phase6-profile "$PHASE6_PROFILE"
    --phase6-video-output-mode "$PHASE6_VIDEO_OUTPUT_MODE"
    --phase6-sidecar-filename "$PHASE6_SIDECAR_FILENAME"
    --workers "$WORKERS"
    --batch-size "$EVENT_BATCH_SIZE"
    --stability-interval "$STABILITY_INTERVAL"
    --stability-timeout "$STABILITY_TIMEOUT"
    --max-load-ratio "$MAX_LOAD_RATIO"
    --min-free-mem-gb "$MIN_FREE_MEM_GB"
    --resource-max-wait-seconds "$RESOURCE_MAX_WAIT_SECONDS"
    --retention-days "$RETENTION_DAYS"
    --retention-max-runs "$RETENTION_MAX_RUNS"
    --retention-max-gb "$RETENTION_MAX_GB"
    --recover-running
  )
  [[ -n "$EVENT_DATE" ]] && args+=(--event-date "$EVENT_DATE")
  [[ -n "$EVENT_DATE_FROM" ]] && args+=(--event-date-from "$EVENT_DATE_FROM")
  [[ -n "$EVENT_DATE_TO" ]] && args+=(--event-date-to "$EVENT_DATE_TO")
  [[ "$DISABLE_QUALITY_LABEL_FILTER" == "1" ]] && args+=(--disable-quality-label-filter)
  exec "$QA_PYTHON" "${args[@]}"
}

status() {
  local process_pid=""
  process_pid="$(managed_process_pid 2>/dev/null || true)"
  if systemd_running; then
    echo "实时检测服务：运行中（托管方式=systemd，服务=$SYSTEMD_SERVICE）"
  elif tmux_running; then
    echo "实时检测服务：运行中（托管方式=tmux，会话=$SESSION）"
  elif [[ -n "$process_pid" ]]; then
    echo "实时检测服务：运行中（托管方式=process，进程号=$process_pid）"
  else
    echo "实时检测服务：未运行"
  fi
  echo "期望状态：$([[ -f "$ENABLED_FILE" ]] && echo 运行 || echo 停止)"
  echo "检测阶段：$PHASES"
  echo "路径映射：NAS=$NAS_PREFIX，服务器挂载=$MOUNT_PREFIX"
  echo "UMI 第 6 阶段：配置=$PHASE6_PROFILE，输出=$PHASE6_VIDEO_OUTPUT_MODE，文件=$PHASE6_SIDECAR_FILENAME"
  echo "是否关闭质量标签预筛选：$DISABLE_QUALITY_LABEL_FILTER"
  if [[ -f "$JOB_DB" ]]; then
    "$QA_PYTHON" Werkzeuge/listen_episode_verified.py status --job-db "$JOB_DB" --limit 10
  else
    echo "任务数据库不存在：$JOB_DB"
  fi
  if [[ -d "$OUTPUT_DIR" ]]; then
    echo
    echo "输出目录大小："
    du -sh "$OUTPUT_DIR" 2>/dev/null || true
  fi
}

case "$ACTION" in
  start)
    mkdir -p "$OUTPUT_DIR" "$CONTROL_DIR"
    if listener_running; then
      echo "实时检测服务已在运行，不会重复启动。"
      echo
      status
      exit 0
    fi
    rm -f "$PID_FILE"
    persist_settings
    "$QA_PYTHON" Werkzeuge/listen_episode_verified.py recover-running --job-db "$JOB_DB" || true
    if [[ "$BACKEND" == "systemd" ]]; then
      if ! systemctl --user enable "$SYSTEMD_SERVICE" >/dev/null; then
        echo "无法启用实时检测 user-systemd 服务：$SYSTEMD_SERVICE"
        exit 1
      fi
      if ! systemctl --user start "$SYSTEMD_SERVICE"; then
        systemctl --user disable "$SYSTEMD_SERVICE" >/dev/null 2>&1 || true
        echo "实时检测 user-systemd 服务启动失败：$SYSTEMD_SERVICE"
        exit 1
      fi
      mark_enabled
      echo "实时检测服务已启动：托管方式=systemd，服务=$SYSTEMD_SERVICE"
      echo "日志：journalctl --user -u $SYSTEMD_SERVICE"
      exit 0
    fi
    if [[ "$BACKEND" == "tmux" ]] && ! command -v tmux >/dev/null 2>&1; then
      echo "已指定 tmux 托管，但系统未安装 tmux。请设置 EVENT_LISTENER_BACKEND=process。"
      exit 1
    fi
    if tmux_available; then
      tmux new-session -d -s "$SESSION" \
        "cd '$REPO_ROOT' && EVENT_LISTENER_USE_SAVED_SETTINGS=1 exec '$0' serve >> '$LOG_FILE' 2>&1"
      manager="tmux"
    else
      EVENT_LISTENER_USE_SAVED_SETTINGS=1 nohup setsid "$0" serve >> "$LOG_FILE" 2>&1 < /dev/null &
      pid="$!"
      printf '%s\n' "$pid" > "$PID_FILE.tmp.$$"
      mv "$PID_FILE.tmp.$$" "$PID_FILE"
      manager="process"
      sleep 1
      if ! managed_process_pid >/dev/null; then
        rm -f "$PID_FILE"
        echo "实时检测服务在启动过程中退出，请查看日志：$LOG_FILE"
        exit 1
      fi
    fi
    mark_enabled
    echo "实时检测服务已启动：托管方式=$manager"
    echo "日志：$LOG_FILE"
    ;;
  stop)
    mark_disabled
    stopped=0
    if [[ "$BACKEND" == "systemd" ]]; then
      if systemctl --user is-active --quiet "$SYSTEMD_SERVICE" 2>/dev/null; then
        systemctl --user stop "$SYSTEMD_SERVICE"
        stopped=1
      fi
      systemctl --user disable "$SYSTEMD_SERVICE" >/dev/null 2>&1 || true
    fi
    if tmux_running; then
      tmux kill-session -t "$SESSION"
      stopped=1
    fi
    pid="$(managed_process_pid 2>/dev/null || true)"
    if [[ -n "$pid" ]]; then
      pgid="$(ps -o pgid= -p "$pid" 2>/dev/null | tr -d '[:space:]' || true)"
      if [[ "$pgid" == "$pid" ]]; then
        kill -TERM -- "-$pid" 2>/dev/null || true
      else
        kill -TERM "$pid" 2>/dev/null || true
      fi
      for _ in {1..30}; do
        kill -0 "$pid" 2>/dev/null || break
        sleep 1
      done
      if kill -0 "$pid" 2>/dev/null; then
        if [[ "$pgid" == "$pid" ]]; then
          kill -KILL -- "-$pid" 2>/dev/null || true
        else
          kill -KILL "$pid" 2>/dev/null || true
        fi
      fi
      stopped=1
    fi
    rm -f "$PID_FILE"
    if [[ "$stopped" == "1" ]]; then echo "实时检测服务已停止。"; else echo "实时检测服务当前未运行。"; fi
    ;;
  restart)
    "$0" stop
    "$0" start
    ;;
  status)
    status
    ;;
  serve)
    start_foreground
    ;;
  log)
    mkdir -p "$OUTPUT_DIR"
    touch "$LOG_FILE"
    tail -f "$LOG_FILE"
    ;;
  *)
    echo "用法：$0 {start|stop|restart|status|log|serve}"
    exit 2
    ;;
esac
